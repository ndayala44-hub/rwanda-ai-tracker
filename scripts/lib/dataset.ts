/**
 * Shared dataset loading for the build scripts.
 *
 * One place defines which files make up the dataset and what each is called in
 * the payload the frontend receives. Adding a dataset means adding one line
 * here, one line in services/api/src/store.ts, and one line in the frontend
 * data layer — nothing else.
 */
import { readFileSync } from "node:fs";
import { join, resolve } from "node:path";

export const FILES = {
  sources: "sources.json",
  organisations: "organisations.json",
  sectors: "sectors.json",
  geography: "geography.json",
  framework: "framework.json",
  indicators: "indicators.json",
  observations: "observations.json",
  journey: "journey.json",
  policies: "policies.json",
  glossary: "glossary.json",
  useCases: "use-cases.json",
  contributions: "contributions.json",
  economicSizing2022: "economic-sizing-2022.json",
  landscape2026: "landscape-2026.json",
  benchmarks: "benchmarks.json",
  proposedIndicators: "proposed-indicators.json"
} as const;

export type DatasetKey = keyof typeof FILES;
export type Dataset = Record<DatasetKey, any> & { generated?: string };

export function dataDir(root: string): string {
  return resolve(process.env.DATA_DIR ?? join(root, "data"));
}

export function readDataset(dir: string): Dataset {
  const out = {} as Dataset;
  for (const [key, file] of Object.entries(FILES)) {
    out[key as DatasetKey] = JSON.parse(readFileSync(join(dir, file), "utf8"));
  }
  out.generated = new Date().toISOString();
  return out;
}

export function summarise(ds: Dataset): string {
  return [
    `${ds.indicators.items.length} indicators`,
    `${ds.observations.items.length} observations`,
    `${ds.sources.items.length} sources`,
    `${ds.useCases.items.length} use cases`,
    `${ds.organisations.items.length} organisations`,
    `${ds.benchmarks.series.length} comparator series`
  ].join(" · ");
}

/**
 * Walk up from the current working directory to the repository root, so the
 * scripts work whether they are run from the root, from a workspace, or from
 * an npm lifecycle hook. `import.meta.dirname` is not reliable across the
 * CJS/ESM transforms the toolchain may apply.
 */
export function repoRoot(): string {
  let dir = process.cwd();
  for (let i = 0; i < 6; i++) {
    try {
      const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
      if (pkg.name === "rwanda-ai-tracker") return dir;
    } catch { /* keep walking */ }
    const parent = resolve(dir, "..");
    if (parent === dir) break;
    dir = parent;
  }
  throw new Error("Could not locate the repository root — run from inside the project");
}

/** Write bootstrap.json and the embedded-dataset module. Shared by both builds. */
export function writeSnapshot(root: string): { dataset: Dataset; kb: string } {
  const { writeFileSync } = require("node:fs") as typeof import("node:fs");
  const dataset = readDataset(dataDir(root));
  const web = join(root, "apps/web");
  writeFileSync(join(web, "data/bootstrap.json"), JSON.stringify(dataset, null, 2));
  writeFileSync(
    join(web, "src/00-embedded-dataset.js"),
    "/* Generated by scripts/build-snapshot.ts — do not edit by hand.\n" +
    "   Offline fallback so the single file still opens without a server. */\n" +
    "const EMBEDDED_DATASET=" + JSON.stringify(dataset) + ";\n"
  );
  return { dataset, kb: (JSON.stringify(dataset).length / 1024).toFixed(0) };
}
